private void calcularSubtotal() {

    try {

        int cantidad =
                Integer.parseInt(
                        txtCantidad.getText()
                );

        double precio =
                Double.parseDouble(
                        txtPrecio.getText()
                );

        double descuento = 0;

        if(!txtDescuento.getText().isEmpty()){

            descuento =
                    Double.parseDouble(
                            txtDescuento.getText()
                    );
        }

        double subtotal =
                (cantidad * precio) - descuento;

        txtSubtotal.setText(
                String.valueOf(subtotal)
        );

    } catch (Exception e) {

        txtSubtotal.setText("");
    }
}
