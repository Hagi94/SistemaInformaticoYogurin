    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
    Venta venta = new Venta();

venta.setClienteId(
        Integer.parseInt(
                txtIdCliente.getText()
        )
);

venta.setTotal(totalVenta);

double descuento = 0;

if(!txtDescuento.getText().isEmpty()){

    descuento =
            Double.parseDouble(
                    txtDescuento.getText()
            );
}

venta.setDescuento(descuento);

venta.setTotalPagar(
        totalVenta - descuento
);

int idVenta =
        ventaDAO.guardarVenta(venta);

for(int i=0;
    i<tblDetalleVenta.getRowCount();
    i++){

    int productoId =
            Integer.parseInt(
                    tblDetalleVenta.getValueAt(i,0).toString()
            );

    int cantidad =
            Integer.parseInt(
                    tblDetalleVenta.getValueAt(i,2).toString()
            );

    double precio =
            Double.parseDouble(
                    tblDetalleVenta.getValueAt(i,3).toString()
            );

    double subtotal =
            Double.parseDouble(
                    tblDetalleVenta.getValueAt(i,4).toString()
            );

    ventaDAO.guardarDetalle(
            idVenta,
            productoId,
            cantidad,
            precio,
            subtotal
    );

    ventaDAO.descontarStock(
            productoId,
            cantidad
    );

    ventaDAO.registrarMovimiento(
            productoId,
            cantidad
    );
}

javax.swing.JOptionPane.showMessageDialog(
        null,
        "Venta registrada correctamente"
);
modelo.setRowCount(0);

txtCantidad.setText("");

txtSubtotal.setText("");

txtTotal.setText("");

txtDescuento.setText("");

totalVenta = 0;
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

