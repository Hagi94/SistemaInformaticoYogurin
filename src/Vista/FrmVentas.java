    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

    String producto =
            cmbProducto.getSelectedItem().toString();
    

    int cantidad =
            Integer.parseInt(
                    txtCantidad.getText()
            );

    double precio =
            Double.parseDouble(
                    txtPrecio.getText()
            );

double descuento = 0;

if(!txtDescuento.getText().isEmpty()){
    descuento = Double.parseDouble(txtDescuento.getText());
}

double subtotal =
        (cantidad * precio) - descuento;

    txtSubtotal.setText(
            String.valueOf(subtotal)
    );

Producto p =
        productoDAO.buscarPorNombre(producto);
if(cantidad > p.getStock()){

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Stock insuficiente"
    );

    return;
}
Object datos[] = {

    p.getId(),
    producto,
    cantidad,
    precio,
    subtotal
};

    modelo.addRow(datos);

    totalVenta += subtotal;

    double descuentoTotal = 0;

    if (!txtDescuento.getText().isEmpty()) {

        descuentoTotal =
                Double.parseDouble(
                        txtDescuento.getText()
                );
    }

    double totalFinal =
            totalVenta - descuentoTotal;

    txtTotal.setText(
            String.valueOf(totalFinal)
    );

    txtCantidad.setText("");
    txtSubtotal.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

