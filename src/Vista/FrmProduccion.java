    public void listarProduccion() {
        modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        List<Produccion> lista = control.listar();

        for (Produccion p : lista) {
            Object datos[] = {
                p.getId(),
                p.getFecha(),
                p.getLote(),
                p.getSabor(),
                p.getCantidad(),
                p.getObservacion(),
                p.getPrecioVenta()
            };
            modelo.addRow(datos);
        }
    }

